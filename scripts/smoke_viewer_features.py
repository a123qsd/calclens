@contextmanager
def workspace_server():
    from slab_preflight.web_api import create_server

    server = create_server(ROOT, 0, "en")
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        yield f"http://{server.expected_host}/"
    finally:
        server.shutdown()
        server.server_close()
        thread.join(timeout=10)


def png_header(path):
    data = path.read_bytes()
    require(data[:8] == b"\x89PNG\r\n\x1a\n", "Downloaded image is not PNG.")
    require(data[12:16] == b"IHDR", "Downloaded PNG has no image header.")
    width, height, depth, color_type = struct.unpack(">IIBB", data[16:26])
    return {"width": width, "height": height, "depth": depth,
            "color_type": color_type, "bytes": len(data)}


def idle(page):
    page.get_by_test_id("app-ready").wait_for(state="visible", timeout=60_000)
    page.wait_for_function("() => !document.querySelector('[aria-label=\"Working\"]')")


def viewer(page, index=0):
    return page.locator(".molecule-viewer").nth(index)


def canvas(page, index=0):
    return viewer(page, index).get_by_test_id("molecule-canvas").locator("canvas").first


def scene_state(page, index=0):
    return canvas(page, index).evaluate("""element => {
        const viewer = element._3dmol_viewer;
        return {view: viewer.getView(), width: element.width, height: element.height,
            atomCount: viewer.getModel(0).selectedAtoms({}).length,
            background: {color: viewer.bgColor, alpha: viewer.renderer._clearAlpha},
            labels: viewer.labels.map(label => ({text: label.text,
                position: label.stylespec.position, visible: label.sprite.visible})),
            shapes: viewer.shapes.filter(Boolean).length};
    }""")


def assert_camera_equal(left, right, message):
    require(len(left) == len(right) and max(abs(a - b) for a, b in zip(left, right)) < 1e-7,
            message)



def selected_entry(page):
    workspace = page.evaluate("async () => (await fetch('/api/v1/workspace')).json()")
    return next(item for item in workspace["entries"]
                if item["id"] == workspace["project"]["selected_id"])


