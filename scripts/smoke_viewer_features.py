def settle(page):
    page.evaluate("() => new Promise(r => requestAnimationFrame(() => requestAnimationFrame(r)))")


def central_atom_colors(page):
    return canvas(page).evaluate("""element => {
        const ctx=document.createElement('canvas').getContext('2d');
        return element._3dmol_viewer.getModel(0).selectedAtoms({})
            .filter(atom => atom.properties.calclensShift.join() === '0,0,0')
            .map(atom => {
                const style=atom.style.sphere;
                // 3Dmol's getColorFromStyle gives colorfunc precedence over color.
                ctx.fillStyle=style.colorfunc ? style.colorfunc(atom) : style.color;
                return {index:atom.properties.calclensIndex, element:atom.elem, color:ctx.fillStyle};
            });
    }""")


def pick_central_atom(page, index, expect):
    canvas(page).scroll_into_view_if_needed()
    point = canvas(page).evaluate("""(element, index) => {
        const v=element._3dmol_viewer;
        const atom=v.getModel(0).selectedAtoms({}).find(a=>a.properties.calclensIndex===index
            && a.properties.calclensShift.join()==='0,0,0');
        const p=v.modelToScreen(atom); return {x:p.x-scrollX,y:p.y-scrollY};
    }""", index)
    page.mouse.click(point["x"], point["y"])
    expect(page.get_by_test_id("viewer-atom-detail")).to_contain_text(f"C{index + 1} · [0, 0, 0]")
    settle(page)


def charge_fixture(entry, kind="partial_charge", values=None):
    report = entry["analysis"]["report"]
    if values is None:
        values = [0.25] + [None] * (report["atom_count"] - 1)
    return {"schema_version": 1, "structure_sha256": entry["sha256"], "kind": kind,
            "method": "Synthetic browser test assignment",
            "source": "Synthetic regression fixture; not a scientific result",
            "atoms": [{"index": index + 1, "element": element, "value": values[index]}
                      for index, element in enumerate(report["elements"])]}


def cube_fixture(report, kind="orbital", bad_coordinates=False, mixed_units=False):
    """A signed analytic test field on a 5×5×5 Å grid; never a calculated orbital."""
    center = [sum(p[axis] for p in report["positions"]) / report["atom_count"]
              for axis in range(3)]
    origin = [component - 2 for component in center]
    rows = ["Synthetic browser regression field, not scientific output",
            "Coordinates in angstrom; scalar orbital units arbitrary",
            f"{report['atom_count']} " + " ".join(f"{value:.10f}" for value in origin),
            "5 1 0 0" if mixed_units else "-5 1 0 0", "-5 0 1 0", "-5 0 0 1"]
    require(all(element == "C" for element in report["elements"]),
            "The synthetic Cube fixture expects the two-carbon example.")
    for index, position in enumerate(report["positions"]):
        point = list(position)
        if bad_coordinates and index == 0:
            point[0] += 0.1
        rows.append("6 6.0 " + " ".join(f"{value:.10f}" for value in point))
    values = []
    for x in range(5):
        for y in range(5):
            for z in range(5):
                dx, dy, dz = x - 2, y - 2, z - 2
                value = dx * math.exp(-0.5 * (dx * dx + dy * dy + dz * dz))
                values.append(abs(value) if kind == "density" else value)
    for offset in range(0, len(values), 5):
        rows.append(" ".join(f"{value:.9e}" for value in values[offset:offset + 5]))
    return "\n".join(rows) + "\n"


def import_file(page, test_id, name, content, mime_type="application/json"):
    payload = content.encode("utf-8") if isinstance(content, str) else content
    page.get_by_test_id(test_id).set_input_files({"name": name, "mimeType": mime_type,
                                                "buffer": payload})
    page.wait_for_function("() => !document.querySelector('.auxiliary-body[aria-busy=true]')")
    settle(page)


def check_file_tab_keyboard(page, expect):
    """Keyboard focus must reveal a whole file tab inside its own scroll region."""
    contents = (ROOT / "examples/graphene.cif").read_bytes()
    page.get_by_test_id("cif-replace-upload").set_input_files([
        {"name": f"{index:02d}_long_filename_연구용_구조_검토_" * 3 + ".cif",
         "mimeType": "chemical/x-cif", "buffer": contents}
        for index in range(20)
    ])
    idle(page)
    page.set_viewport_size({"width": 390, "height": 844})
    results = []
    for language in ("ko", "en"):
        if page.locator("html").get_attribute("lang") != language:
            page.get_by_test_id("language-toggle").click()
            idle(page)
        tabs = page.locator(".file-tab")
        expect(tabs).to_have_count(20)
        tabs.first.focus()
        for _ in range(19):
            page.keyboard.press("Tab")
        expect(tabs.last).to_be_focused()
        geometry = tabs.last.evaluate("""element => {
            const tab = element.getBoundingClientRect();
            const rail = element.parentElement.getBoundingClientRect();
            return {left: tab.left, right: tab.right, railLeft: rail.left,
                railRight: rail.right, overflow: document.documentElement.scrollWidth - innerWidth};
        }""")
        require(geometry["left"] >= geometry["railLeft"] - 1
                and geometry["right"] <= geometry["railRight"] + 1,
                f"{language}: focused last file tab is clipped: {geometry!r}")
        require(geometry["overflow"] <= 1, "File tabs overflow the page.")
        expect(tabs.first).to_have_attribute("aria-pressed", "true")
        page.keyboard.press("Enter")
        idle(page)
        expect(tabs.last).to_have_attribute("aria-pressed", "true")
        # Restore selection so the next language pass has the same starting state.
        tabs.first.click()
        idle(page)
        results.append({"language": language, "files": 20, "keyboard_reveal": True,
                        "keyboard_activation": True, **geometry})
    page.set_viewport_size({"width": 1584, "height": 1000})
    return results


def check_layout(page, output, expect):
    results = []
    for language in ("en", "ko"):
        if page.locator("html").get_attribute("lang") != language:
            page.get_by_test_id("language-toggle").click()
            idle(page)
        for width in (390, 820, 1100, 1584):
            page.set_viewport_size({"width": width, "height": 1000})
            settle(page)
            geometry = page.evaluate("""() => {
                const first = document.querySelector('.sample-control select').getBoundingClientRect();
                const second = document.querySelector('.sample-control button').getBoundingClientRect();
                const overlap = Math.min(first.right, second.right) - Math.max(first.left, second.left);
                return {overflow: document.documentElement.scrollWidth - innerWidth,
                    overlap: overlap > 0 && Math.min(first.bottom, second.bottom) > Math.max(first.top, second.top)
                        ? overlap : 0};
            }""")
            require(geometry["overflow"] <= 1, f"{language}/{width}: page overflows {geometry!r}")
            require(geometry["overlap"] <= 1, f"{language}/{width}: sample controls overlap {geometry!r}")
            expect(canvas(page)).to_be_visible()
            results.append({"language": language, "width": width, **geometry})
            page.screenshot(path=str(output / f"layout-{language}-{width}.png"), full_page=True)
    if page.locator("html").get_attribute("lang") != "en":
        page.get_by_test_id("language-toggle").click()
        idle(page)
    page.set_viewport_size({"width": 1584, "height": 1000})
    return results


def instrument(page, index=0):
    return canvas(page, index).evaluate("""element => {
        const viewer = element._3dmol_viewer;
        const probe = {viewer, baseModel: viewer.getModel(0), rebuilds: 0, isosurfaces: []};
        window.__featureProbe = probe;
        const remove = viewer.removeAllModels;
        viewer.removeAllModels = function(...args) {probe.rebuilds++; return remove.apply(this, args);};
        const isosurface = viewer.addIsosurface;
        viewer.addIsosurface = function(data, specification, ...rest) {
            const shape = isosurface.call(this, data, specification, ...rest);
            probe.isosurfaces.push({isoval: specification.isoval, color: specification.color,
                size: data.size, origin: data.origin, count: data.data.length,
                finite: [...data.data].every(Number.isFinite), shape});
            return shape;
        };
        return {atomCount: probe.baseModel.selectedAtoms({}).length};
    }""")


def unchanged_atoms(page):
    require(page.evaluate("window.__featureProbe.baseModel === window.__featureProbe.viewer.getModel(0)"),
            "A presentation-only control replaced the atom model.")
    require(page.evaluate("window.__featureProbe.rebuilds") == 0,
            "A presentation-only control rebuilt all models.")


def check_presentation(page, output, expect):
    open_settings(page)
    instrument(page)
    original = scene_state(page)
    for representation in ("stick", "spacefill", "ball-stick"):
        page.get_by_test_id("viewer-representation").select_option(representation)
        settle(page)
        styles = canvas(page).evaluate("element => element._3dmol_viewer.getModel(0).selectedAtoms({}).map(a => a.style)")
        if representation == "spacefill":
            require(all("sphere" in style and "stick" not in style for style in styles),
                    "Space filling did not replace ball-and-stick styling.")
        elif representation == "ball-stick":
            require(all("sphere" in style and "stick" in style for style in styles),
                    "Ball-and-stick styling is incomplete.")
        else:
            require(all("stick" in style for style in styles), "Stick mode has no sticks.")
        unchanged_atoms(page)
    for quality in ("light", "high", "balanced"):
        page.get_by_test_id("viewer-quality").select_option(quality)
        settle(page)
        unchanged_atoms(page)
        current = scene_state(page)
        require(current["atomCount"] == original["atomCount"], "Graphics quality omitted atoms.")
        assert_camera_equal(original["view"], current["view"], "Graphics quality changed the camera.")
    views = []
    for preset in ("top", "side", "default"):
        page.get_by_test_id("viewer-preset").select_option(preset)
        settle(page)
        views.append(scene_state(page)["view"])
        unchanged_atoms(page)
    require(max(abs(a-b) for a, b in zip(views[0][4:8], views[1][4:8])) > 0.1,
            "Top and side presets have the same orientation.")
    for projection in ("orthographic", "perspective"):
        page.get_by_test_id("viewer-projection").select_option(projection)
        settle(page)
        orthographic = canvas(page).evaluate("element => element._3dmol_viewer.camera.ortho")
        require(bool(orthographic) == (projection == "orthographic"), "Projection did not change the camera.")
        unchanged_atoms(page)
    old_height = canvas(page).bounding_box()["height"]
    page.get_by_test_id("viewer-expanded").click()
    settle(page)
    require(canvas(page).bounding_box()["height"] > old_height + 30, "Expanded view did not grow.")
    page.get_by_test_id("viewer-expanded").click()
    settle(page)
    require(abs(canvas(page).bounding_box()["height"] - old_height) < 2, "Expanded view did not restore.")
    unchanged_atoms(page)
    expect(page.get_by_test_id("viewer-counts")).to_contain_text("18")
    expect(page.get_by_test_id("viewer-legend")).to_contain_text("C")
    for preset in ("top", "side"):
        page.get_by_test_id("viewer-preset").select_option(preset)
        settle(page)
        orientation = scene_state(page)["view"][4:8]
        for repeat in (1, 3):
            viewer(page).locator(".molecule-toolbar select").select_option(str(repeat))
            settle(page)
            expect(page.get_by_test_id("viewer-preset")).to_have_value(preset)
            state = scene_state(page)
            assert_camera_equal(orientation, state["view"][4:8],
                                f"{preset} orientation was lost when changing repeat to {repeat}.")
            require(state["atomCount"] == 2 * repeat * repeat, "Repeat did not update the fitted atom set.")
    page.get_by_test_id("viewer-preset").select_option("default")
    settle(page)
    page.screenshot(path=str(output / "presentation.png"), full_page=True)
    return {"representations": 3, "qualities": 3, "camera_presets": 3,
            "projections": 2, "atom_count": original["atomCount"], "presentation_rebuilds": 0,
            "named_preset_survives_repeat": True}


def check_charges(page, output, expect):
    open_auxiliary(page)
    entry = selected_entry(page)
    with page.expect_download() as pending:
        page.get_by_test_id("charge-template").click()
    template_path = output / "charge-template.json"
    pending.value.save_as(template_path)
    template = json.loads(template_path.read_text())
    require(template["structure_sha256"] == entry["sha256"], "Charge template has the wrong CIF identity.")
    require(all(atom["value"] is None for atom in template["atoms"]),
            "Charge template fabricated zero values for unknown charges.")
    partial = charge_fixture(entry)
    import_file(page, "charge-import", "synthetic-partial-charge.json", json.dumps(partial))
    expect(page.get_by_test_id("auxiliary-error")).to_have_count(0)
    open_settings(page)
    page.get_by_test_id("viewer-color").select_option("partial_charge")
    settle(page)
    expect(page.get_by_test_id("viewer-legend")).to_contain_text("Partial")
    expect(page.get_by_test_id("viewer-legend")).to_contain_text("Synthetic browser test")
    expect(page.get_by_test_id("viewer-legend")).to_contain_text(re.compile("unknown", re.I))
    colors = central_atom_colors(page)
    require([atom["index"] for atom in colors] == [0, 1], "Charge check selected the wrong original atoms.")
    require(len({atom["color"] for atom in colors}) == 2,
            "A missing partial charge was colored as the supplied positive value.")
    legend_colors = page.get_by_test_id("viewer-legend").evaluate("""element => {
        const ctx=document.createElement('canvas').getContext('2d');
        return [...element.querySelectorAll('span')].filter(span=>span.querySelector('.legend-dot'))
            .map(span=>{ctx.fillStyle=span.querySelector('.legend-dot').style.background;
                return {text:span.textContent.trim(), color:ctx.fillStyle};});
    }""")
    unknown_color = next(item["color"] for item in legend_colors if item["text"] == "Unknown")
    neutral_color = next(item["color"] for item in legend_colors if item["text"] == "0")
    require(colors[1]["color"] == unknown_color and unknown_color != neutral_color,
            "Unknown partial charge is not distinct from a known neutral charge.")
    rejected = []
    invalid_documents = []
    wrong_sha = json.loads(json.dumps(partial))
    wrong_sha["structure_sha256"] = "0" * 64
    invalid_documents.append(("wrong-sha", wrong_sha))
    wrong_element = json.loads(json.dumps(partial))
    wrong_element["atoms"][0]["element"] = "O"
    invalid_documents.append(("wrong-element", wrong_element))
    missing_value = json.loads(json.dumps(partial))
    del missing_value["atoms"][1]["value"]
    invalid_documents.append(("missing-value", missing_value))
    no_method = json.loads(json.dumps(partial))
    no_method["method"] = ""
    invalid_documents.append(("missing-method", no_method))
    invalid_documents.append(("fractional-formal", charge_fixture(entry, "formal_charge", [0.5, -0.5])))
    for name, document in invalid_documents:
        import_file(page, "charge-import", f"synthetic-invalid-{name}.json", json.dumps(document))
        expect(page.get_by_test_id("auxiliary-error")).to_contain_text("Existing data is unchanged")
        current_colors = central_atom_colors(page)
        require(current_colors == colors, f"Rejected {name} data replaced the last valid charges.")
        rejected.append(name)
    for kind, values, label in (("formal_charge", [1, -1], "formal"),
                                ("ionic_charge", [1, -1], "Ionic"),
                                ("oxidation_state", [2, -2], "Oxidation")):
        import_file(page, "charge-import", f"synthetic-{kind}.json", json.dumps(charge_fixture(entry, kind, values)))
        expect(page.get_by_test_id("auxiliary-error")).to_have_count(0)
        page.get_by_test_id("viewer-color").select_option(kind)
        settle(page)
        expect(page.get_by_test_id("viewer-legend")).to_contain_text(re.compile(label, re.I))
    page.get_by_test_id("viewer-color").select_option("partial_charge")
    page.get_by_test_id("viewer-preset").select_option("top")
    viewer(page).locator(".molecule-toolbar select").select_option("1")
    settle(page)
    instrument(page)
    pick_central_atom(page, 0, expect)
    require(central_atom_colors(page)[0]["color"] == "#f59e0b", "Charge color masked the selected atom's amber highlight.")
    page.get_by_test_id("viewer-color").select_option("element")
    settle(page)
    require(central_atom_colors(page)[0]["color"] == "#f59e0b", "Element color masked the selected atom's amber highlight.")
    pick_central_atom(page, 1, expect)
    picked_colors = central_atom_colors(page)
    require(picked_colors[0]["color"] != "#f59e0b" and picked_colors[1]["color"] == "#f59e0b",
            "Changing the picked atom left the old amber highlight or omitted the new one.")
    page.get_by_test_id("viewer-color").select_option("partial_charge")
    settle(page)
    picked_colors = central_atom_colors(page)
    require(picked_colors[0]["color"] == colors[0]["color"] and picked_colors[1]["color"] == "#f59e0b",
            "Charge color or selected highlight was not restored after changing color modes.")
    expect(page.get_by_test_id("viewer-atom-detail")).to_contain_text("Unknown")
    unchanged_atoms(page)
    viewer(page).locator(".molecule-toolbar select").select_option("3")
    page.get_by_test_id("viewer-preset").select_option("default")
    settle(page)
    page.screenshot(path=str(output / "charge-data.png"), full_page=True)
    return {"template_unknown_values": True, "accepted_kinds": 4, "rejected": rejected,
            "unknown_distinct_color": True, "resolved_selection_color": "amber in element and charge modes"}


def check_volume(page, output, expect):
    open_auxiliary(page)
    entry = selected_entry(page)
    report = entry["analysis"]["report"]
    page.get_by_test_id("volume-kind").select_option("orbital")
    page.get_by_test_id("volume-units").select_option("arbitrary")
    page.get_by_test_id("volume-source").fill("Synthetic analytic test field; not a calculated orbital")
    text = cube_fixture(report)
    import_file(page, "volume-import", "synthetic-orbital.cube", text, "text/plain")
    expect(page.get_by_test_id("auxiliary-error")).to_have_count(0)
    open_settings(page)
    instrument(page)
    page.get_by_test_id("viewer-volume-enabled").check()
    page.wait_for_function("() => window.__featureProbe.isosurfaces.length >= 2")
    surfaces = page.evaluate("""() => window.__featureProbe.isosurfaces.map(({shape, ...data}) => ({...data,
        vertexCount: shape.geo.geometryGroups.reduce((n, group) => n + group.vertices, 0)}))""")
    require(len(surfaces) == 2 and surfaces[0]["isoval"] * surfaces[1]["isoval"] < 0,
            f"Orbital import did not create positive and negative isosurfaces: {surfaces!r}")
    require(all(s["count"] == 125 and s["finite"] and s["vertexCount"] > 0 for s in surfaces),
            "A real 5×5×5 volume was not passed into the renderer or produced empty surfaces.")
    expect(viewer(page)).to_contain_text("Wavefunction sign")
    count = page.evaluate("window.__featureProbe.isosurfaces.length")
    for action in ("Atom IDs", "Atom IDs", "Unit cell", "Unit cell"):
        viewer(page).get_by_title(action, exact=True).click()
        settle(page)
    page.get_by_test_id("viewer-representation").select_option("spacefill")
    page.get_by_test_id("viewer-representation").select_option("ball-stick")
    page.get_by_test_id("viewer-quality").select_option("high")
    page.get_by_test_id("viewer-quality").select_option("balanced")
    settle(page)
    require(page.evaluate("window.__featureProbe.isosurfaces.length") == count,
            "Presentation controls rebuilt unchanged electronic surfaces.")
    unchanged_atoms(page)
    page.get_by_test_id("viewer-volume-enabled").uncheck()
    page.get_by_test_id("viewer-volume-enabled").check()
    settle(page)
    require(page.evaluate("window.__featureProbe.isosurfaces.length") == count,
            "Hiding and showing a volume rebuilt an unchanged surface.")
    page.get_by_test_id("viewer-opacity").fill("0.55")
    page.get_by_test_id("viewer-surface-apply").click()
    settle(page)
    require(page.evaluate("window.__featureProbe.isosurfaces.length") == count,
            "Opacity-only Apply regenerated the surface geometry.")
    require(page.evaluate("window.__featureProbe.isosurfaces.every(item => Math.abs(item.shape.opacity - 0.55) < 1e-8)"),
            "Opacity-only Apply did not update the displayed surfaces.")
    isovalue = page.get_by_test_id("viewer-isovalue")
    new_isovalue = str(float(isovalue.input_value()) * 1.25)
    isovalue.fill(new_isovalue)
    settle(page)
    require(page.evaluate("window.__featureProbe.isosurfaces.length") == count,
            "Editing an unapplied isovalue rebuilt the surfaces.")
    page.get_by_test_id("viewer-surface-apply").click()
    page.wait_for_function("() => window.__featureProbe.isosurfaces.length === 4")
    require(page.evaluate("window.__featureProbe.viewer.getModel(0).selectedAtoms({}).length") == 18,
            "Orbital display altered the periodic atom set.")
    for name, bad_text in (("coordinates", cube_fixture(report, bad_coordinates=True)),
                            ("units", cube_fixture(report, mixed_units=True))):
        import_file(page, "volume-import", f"synthetic-invalid-{name}.cube", bad_text, "text/plain")
