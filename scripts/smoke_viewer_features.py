def run(base_url, output):
    from playwright.sync_api import expect, sync_playwright

    output.mkdir(parents=True, exist_ok=True)
    result = {"status": "failed", "checks": [], "events": {"page_errors": [], "console_errors": []}}
    with sync_playwright() as pw:
        browser = pw.chromium.launch(headless=True, args=[
            "--enable-webgl", "--ignore-gpu-blocklist", "--enable-unsafe-swiftshader",
        ])
        context = browser.new_context(accept_downloads=True, viewport={"width": 1584, "height": 1000})
        context.set_default_timeout(30_000)
        context.tracing.start(screenshots=True, snapshots=True, sources=False)
        page = context.new_page()
        page.on("dialog", accept_workspace_dialog)
        page.on("pageerror", lambda error: result["events"]["page_errors"].append(str(error)))
        page.on("console", lambda message: result["events"]["console_errors"].append(message.text)
                if message.type == "error" else None)
        try:
            page.goto(base_url, wait_until="domcontentloaded", timeout=60_000)
            idle(page)
            expect(canvas(page)).to_be_visible()
            expect(page.locator(".molecule-fallback")).to_have_count(0)
            print("Checking keyboard navigation through 20 file tabs", flush=True)
            tab_detail = check_file_tab_keyboard(page, expect)
            result["checks"].append({"name": "keyboard navigation through 20 file tabs",
                                     "status": "passed", "detail": tab_detail})
            primary_name = "graphene_long_filename_연구용_구조_검토_" * 4 + ".cif"
            page.get_by_test_id("cif-replace-upload").set_input_files([
                {"name": primary_name, "mimeType": "chemical/x-cif", "buffer": (ROOT / "examples/graphene.cif").read_bytes()},
                {"name": "mos2.cif", "mimeType": "chemical/x-cif", "buffer": (ROOT / "examples/mos2.cif").read_bytes()},
            ])
            idle(page)
            choose_source(page, primary_name)

            def record(name, operation):
                print(f"Checking {name}", flush=True)
                detail = operation()
                result["checks"].append({"name": name, "status": "passed", "detail": detail})

            record("responsive overview and long filenames", lambda: check_layout(page, output, expect))
            record("presentation controls preserve atoms", lambda: check_presentation(page, output, expect))
            record("fullscreen and review panel", lambda: check_fullscreen_and_panel(page, expect))
            record("charge imports and scientific meaning", lambda: check_charges(page, output, expect))
            record("signed orbital surfaces and cache", lambda: check_volume(page, output, expect))
            record("actual high-resolution PNG and restoration", lambda: check_png(page, output, expect))
            record("per-source data and metal-element color", lambda: check_source_identity_and_metal(page, primary_name, expect))
            record("comparison synchronization and container layout", lambda: check_compare(page, output, expect))
            record("replacement invalidates auxiliary identity", lambda: check_replacement_identity(page, expect))
            require(not result["events"]["page_errors"], f"Page errors: {result['events']['page_errors']}")
            require(not result["events"]["console_errors"], f"Console errors: {result['events']['console_errors']}")
            result["status"] = "passed"
        except Exception as error:
            result["error"] = str(error)
            result["traceback"] = traceback.format_exc()
            page.screenshot(path=str(output / "failure.png"), full_page=True)
            raise
        finally:
            (output / "report.json").write_text(json.dumps(result, ensure_ascii=False, indent=2),
                                                encoding="utf-8")
            context.tracing.stop(path=str(output / "trace.zip"))
            context.close()
            browser.close()
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--url", help="Existing local workspace server; otherwise start a temporary one")
    parser.add_argument("--output", type=Path,
                        default=ROOT.parent.parent / "work" / "browser" / "viewer-features")
    args = parser.parse_args()
    output = args.output.resolve()
    if args.url:
        result = run(args.url, output)
    else:
        with workspace_server() as url:
            result = run(url, output)
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
