"""Generate original, idealized teaching fixtures; requires only Python's stdlib.

These coordinates are mathematical constructions, not copied crystallographic
records or experimental/relaxed structures. See examples/README.md.
"""

import argparse
from pathlib import Path


def cif(name, cell, sites, *, number=1, symbol="P 1"):
    """Write explicit fractional sites without symmetry expansion/deduplication."""
    a, b, c, alpha, beta, gamma = cell
    header = f"""# Original idealized geometry generated by scripts/generate_examples.py.
# Lengths are angstrom; angles are degrees; sites use fractional coordinates.
# Illustrative geometry only: not an experimental or relaxed structure.
data_{name}
_cell_length_a {a:.12g}
_cell_length_b {b:.12g}
_cell_length_c {c:.12g}
_cell_angle_alpha {alpha:.12g}
_cell_angle_beta {beta:.12g}
_cell_angle_gamma {gamma:.12g}
_space_group_IT_number {number}
_space_group_name_H-M_alt '{symbol}'
loop_
_space_group_symop_operation_xyz
'x,y,z'
loop_
_atom_site_label
_atom_site_type_symbol
_atom_site_fract_x
_atom_site_fract_y
_atom_site_fract_z
_atom_site_occupancy
"""
    rows = [
        f"{element}{i} {element} {x:.12g} {y:.12g} {z:.12g} {occupancy:.12g}"
        for i, (element, x, y, z, occupancy) in enumerate(sites, 1)
    ]
    return header + "\n".join(rows) + "\n"


def examples():
    graphene_cell = (2.46, 2.46, 20.0, 90.0, 90.0, 120.0)
    graphene = [("C", 0, 0, 0.5, 1), ("C", 1 / 3, 2 / 3, 0.5, 1)]
    hbn = [("B", 0, 0, 0.5, 1), ("N", 1 / 3, 2 / 3, 0.5, 1)]
    mos2 = [
        ("Mo", 0, 0, 0.5, 1),
        ("S", 1 / 3, 2 / 3, 0.578, 1),
        ("S", 1 / 3, 2 / 3, 0.422, 1),
    ]
    mos2_cell = (3.18, 3.18, 20.0, 90.0, 90.0, 120.0)
    return {
        "graphene.cif": cif("ideal_graphene", graphene_cell, graphene),
        "hbn.cif": cif("ideal_hbn", (2.50, 2.50, 20, 90, 90, 120), hbn),
        "mos2.cif": cif("ideal_mos2", mos2_cell, mos2),
        "graphene_duplicate.cif": cif(
            "duplicate_site", graphene_cell, graphene + [("C", 0, 0, 0.5, 1)]
        ),
        "graphene_short_contact.cif": cif(
            "short_contact", graphene_cell, graphene + [("C", 0.02, 0, 0.5, 1)]
        ),
        "graphene_boundary_duplicate.cif": cif(
            "periodic_duplicate", graphene_cell, graphene + [("C", 1, 0, 0.5, 1)]
        ),
        "mos2_wrapped.cif": cif(
            "wrapped_mos2", mos2_cell,
            [(el, x, y, (z + 0.5) % 1.0, occ) for el, x, y, z, occ in mos2],
        ),
        "partial_occupancy.cif": cif(
            "partial_occupancy", graphene_cell,
            [("C", 0, 0, 0.5, 0.5), graphene[1]],
        ),
        "tilted_c.cif": cif(
            "tilted_c", (2.46, 2.46, 20, 90, 80, 120), graphene,
        ),
        "symmetry_unsupported.cif": cif(
            "non_p1", graphene_cell, graphene, number=194, symbol="P 63/m m c",
        ),
        "multiple_blocks.cif": (
            cif("graphene", graphene_cell, graphene)
            + cif("hbn", (2.50, 2.50, 20, 90, 90, 120), hbn)
        ),
        "bilayer_graphene.cif": cif(
            "bilayer_ambiguity", graphene_cell,
            [(el, x, y, z, occ) for z in (0.30, 0.70)
             for el, x, y, _, occ in graphene],
        ),
        "tiny_self_image.cif": cif(
            "short_self_image", (0.5, 3, 20, 90, 90, 90), [("C", 0, 0, 0.5, 1)],
        ),
        "no_unique_gap.cif": cif(
            "ambiguous_axis", (4, 4, 8, 90, 90, 90),
            [("C", 0, 0, z, 1) for z in (0, 0.25, 0.5, 0.75)],
        ),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check committed files without changing them.")
    args = parser.parse_args()
    destination = Path(__file__).resolve().parents[1] / "examples"
    if args.check:
        different = [
            filename for filename, content in examples().items()
            if not (destination / filename).is_file()
            or (destination / filename).read_text(encoding="utf-8") != content
        ]
        if different:
            parser.exit(1, "Missing or changed fixtures: " + ", ".join(different) + "\n")
        print(f"All {len(examples())} committed CIF fixtures match the generator.")
        return
    destination.mkdir(exist_ok=True)
    for filename, content in examples().items():
        (destination / filename).write_text(content, encoding="utf-8")
    print(f"Wrote {len(examples())} deterministic CIF fixtures to examples/.")


if __name__ == "__main__":
    main()
